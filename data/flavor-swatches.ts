/** Hex to the same color mixed toward white (amount 0 to 1). */
function tint(hex: string, amount: number) {
  const n = parseInt(hex.slice(1), 16);
  const mix = (c: number) => Math.round(c + (255 - c) * amount);
  const r = mix(n >> 16), g = mix((n >> 8) & 255), b = mix(n & 255);
  return `#${((1 << 24) | (r << 16) | (g << 8) | b).toString(16).slice(1)}`;
}

function wordPattern(word: string) {
  return new RegExp(`(^|[^a-z])${word.replace(/ /g, "[^a-z]+")}(?=$|[^a-z])`);
}

const PATTERNS = SWATCH_WORDS.map(([word, color]) => [wordPattern(word), color] as const);

/** Two colors for a flavor's swatch: what it names first, then what it names second (or a lighter tint). */
export function swatchFor(name: string, familySlug: string): [string, string] {
  let rest = ` ${name.toLowerCase().replace(/&/g, "and")} `;
  const found: string[] = [];
  for (const [pattern, color] of PATTERNS) {
    if (found.length === 2) break;
    if (pattern.test(rest)) {
      found.push(color);
      rest = rest.replace(pattern, " ");
    }
  }
  const first = found[0] ?? accentFor(familySlug);
  return [first, found[1] ?? tint(first, 0.38)];
}

/** Perceived lightness, used to pick dark or light text on a swatch. */
export function isLightColor(hex: string) {
  const n = parseInt(hex.slice(1), 16);
  const r = n >> 16, g = (n >> 8) & 255, b = n & 255;
  return 0.299 * r + 0.587 * g + 0.114 * b > 165;
}
